local W=require("tests.mocks.world"); local G=require("lib.genetics"); local C=require("lib.config").defaults()
test("active-only target drone is not success",function()
  local p=W.bee("Spirit","princess"); local d=W.bee("Spirit","drone",8,"Aware")
  eq(G.purity(d,"spirit"),1); ok(not G.complete(p,d,"spirit",C))
end)
test("pure pair completion and separate full gene equivalence",function()
  local p=W.bee("Spirit","princess"); local d=W.bee("Spirit","drone",8,nil,{fertility=4})
  ok(G.complete(p,d,"spirit",C)); local full=require("lib.util").copy(C); full.fullEquivalence=true
  ok(not G.complete(p,d,"spirit",full)); ok(G.equivalent(p,W.bee("Spirit","drone")))
end)
test("genetic identity preserves inactive alleles",function()
  local B=require("lib.bees")
  ok(B.identity(W.bee("Spirit","drone",8,"Aware"))~=B.identity(W.bee("Spirit","drone",8,"Ethereal")))
end)
test("template genes exclude desired species separately",function()
  local p=W.bee("Spirit","princess"); local t=W.bee("Forest","drone")
  ok(G.templateMatch(p,t.individual.active)); t.individual.active.fertility=4; ok(not G.templateMatch(p,t.individual.active))
end)
test("species score dominates fertility preference",function()
  ok(G.score(W.bee("Spirit","drone"),"spirit",C)>G.score(W.bee("Aware","drone",64,nil,{fertility=100}),"spirit",C))
end)
